const BY_ID = new Map(WHY_CARDS.map((c) => [c.id, c]));
export const WHY_IDS: readonly string[] = WHY_CARDS.map((c) => c.id);

/** 그 id 들의 카드 (모르는 id 는 건너뛴다) */
export function whyCards(ids: readonly string[] | undefined): WhyCard[] {
  return (ids ?? []).map((id) => BY_ID.get(id)).filter((c): c is WhyCard => c !== undefined);
}
